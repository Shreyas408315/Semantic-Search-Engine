from __future__ import annotations

from pathlib import Path
from typing import Any

import chromadb

from .config import CHROMA_DIR, MODELS
from .embeddings import embed_documents, embed_query
from .ingestion import TextChunk


class VectorStore:
    def __init__(self, persist_directory: Path = CHROMA_DIR):
        self.client = chromadb.PersistentClient(path=str(persist_directory))

    def get_collection(self, model_key: str):
        if model_key not in MODELS:
            raise ValueError(f"Unknown model: {model_key}")
        return self.client.get_or_create_collection(
            name=MODELS[model_key]["collection"],
            metadata={"hnsw:space": "cosine", "embedding_model": MODELS[model_key]["model_id"]},
            embedding_function=None,  # All document and query vectors are generated by Sentence Transformers.
        )

    def index_chunks(self, chunks: list[TextChunk], model_key: str) -> int:
        if not chunks:
            return 0
        collection = self.get_collection(model_key)
        batch_size = 128
        for start in range(0, len(chunks), batch_size):
            batch = chunks[start : start + batch_size]
            texts = [item.text for item in batch]
            embeddings = embed_documents(texts, model_key)
            collection.upsert(
                ids=[item.chunk_id for item in batch],
                documents=texts,
                metadatas=[item.metadata for item in batch],
                embeddings=embeddings.tolist(),
            )
        return len(chunks)

    @staticmethod
    def _build_where(
        file_type: str | None = None,
        source: str | None = None,
        page_min: int | None = None,
        page_max: int | None = None,
    ) -> dict[str, Any] | None:
        conditions: list[dict[str, Any]] = []
        if file_type and file_type.lower() in {"pdf", "txt"}:
            conditions.append({"file_type": {"$eq": file_type.lower()}})
        if source and source.strip():
            conditions.append({"source": {"$eq": source.strip()}})
        if page_min is not None:
            conditions.append({"page": {"$gte": int(page_min)}})
        if page_max is not None:
            conditions.append({"page": {"$lte": int(page_max)}})
        if not conditions:
            return None
        if len(conditions) == 1:
            return conditions[0]
        return {"$and": conditions}

    def search(
        self,
        query: str,
        model_key: str = "minilm",
        top_k: int = 5,
        file_type: str | None = None,
        source: str | None = None,
        page_min: int | None = None,
        page_max: int | None = None,
    ) -> list[dict[str, Any]]:
        query = query.strip()
        if not query:
            raise ValueError("Enter a search query.")
        if not 1 <= int(top_k) <= 20:
            raise ValueError("top_k must be between 1 and 20.")
        if page_min is not None and page_max is not None and page_min > page_max:
            raise ValueError("Minimum page cannot be greater than maximum page.")

        collection = self.get_collection(model_key)
        if collection.count() == 0:
            return []

        query_embedding = embed_query(query, model_key)
        where = self._build_where(file_type, source, page_min, page_max)
        result = collection.query(
            query_embeddings=[query_embedding.tolist()],
            n_results=min(int(top_k), collection.count()),
            where=where,
            include=["documents", "metadatas", "distances"],
        )

        matches: list[dict[str, Any]] = []
        ids = result.get("ids", [[]])[0]
        docs = result.get("documents", [[]])[0]
        metas = result.get("metadatas", [[]])[0]
        distances = result.get("distances", [[]])[0]
        for chunk_id, document, metadata, distance in zip(ids, docs, metas, distances):
            # Chroma cosine distance is 1 - cosine similarity for normalized vectors.
            similarity = max(-1.0, min(1.0, 1.0 - float(distance)))
            matches.append(
                {
                    "id": chunk_id,
                    "text": document,
                    "metadata": metadata or {},
                    "distance": float(distance),
                    "similarity": similarity,
                }
            )
        return matches

    def list_sources(self, model_key: str | None = None) -> list[str]:
        keys = [model_key] if model_key else list(MODELS)
        sources: set[str] = set()
        for key in keys:
            collection = self.get_collection(key)
            if collection.count() == 0:
                continue
            rows = collection.get(include=["metadatas"])
            for metadata in rows.get("metadatas") or []:
                if metadata and metadata.get("source"):
                    sources.add(str(metadata["source"]))
        return sorted(sources)

    def collection_stats(self) -> dict[str, int]:
        return {key: self.get_collection(key).count() for key in MODELS}
